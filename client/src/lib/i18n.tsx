const DICTS: Record<Lang, Dict> = { en, so, am, om, sw, ar };

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  ready: boolean;
}

const Ctx = createContext<I18nCtx>({
  lang: "en",
  setLang: () => {},
  t: (k) => k,
  ready: false,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const saved = localStorage.getItem("fikrado-lang") as Lang | null;
    if (saved && DICTS[saved]) {
      setLangState(saved);
      setReady(true);
      return;
    }

    // Geo-detect via free API
    fetch("https://ipapi.co/json/")
      .then((r) => r.json())
      .then((data: { country_code?: string }) => {
        const cc = data.country_code?.toUpperCase() ?? "";
        const detected = COUNTRY_LANG[cc] ?? "en";
        setLangState(detected);
        localStorage.setItem("fikrado-lang", detected);
      })
      .catch(() => {
        setLangState("en");
      })
      .finally(() => setReady(true));
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("fikrado-lang", l);
  };

  const t = (key: string) => DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;

  return (
    <Ctx.Provider value={{ lang, setLang, t, ready }}>
      {children}
    </Ctx.Provider>
  );
}

export function useI18n() {
  return useContext(Ctx);
}
